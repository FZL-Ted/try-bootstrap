/* tcbuild.c - drive a musl build with the bootstrapped tcc.
 *
 * A kaem script has no loops, can pass at most about 500 arguments to one
 * command, and the boot libc never frees memory (so a single compiler
 * process can only be given a handful of files).  This program is compiled
 * by tcc-boot3 and takes over the list handling and the process spawning:
 *
 *   tcbuild c <cc> <cflags|-> <root> <objdir> <list>
 *       Compile every source named in <list> (a path relative to <root>, one
 *       per line, '#' comments allowed) into <objdir>, with one <cc> process
 *       per file.  A file that does not compile is reported and skipped: the
 *       boot libc understands only a few floating point literals, so pass 1
 *       cannot build musl's maths.  That partial libc is only used to link
 *       tcc-musl; pass 2 uses tcc-musl, whose runtime is complete, and then
 *       every file builds.
 *       <cflags> names a file holding extra compiler flags (tcc expands
 *       @file); "-" means none.
 *
 *   tcbuild a <cc> - <root> <objdir> <archive> <list>
 *       Archive the objects that exist.  All of them go to a single
 *       "<cc> -ar -cr" command, which is what the kaem argument limit
 *       otherwise prevents; tcc's ar (patched to index STB_WEAK symbols)
 *       writes the symbol index the linker needs.
 *
 * The list is generated by prepare-rootfs.sh, so the build script itself
 * contains no file list at all.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ---- the few system calls we need ---------------------------------------
 * The boot libc (pnut's portable_libc) has no fork/execve/waitpid and no
 * directory creation, so ask the kernel directly; musl uses the same
 * "int $0x80" idiom and tcc assembles it fine.
 */
static int sys0(int n)
{
    int r;
    __asm__ volatile("int $0x80" : "=a"(r) : "a"(n) : "memory");
    return r;
}

static int sys1(int n, int a)
{
    int r;
    __asm__ volatile("int $0x80" : "=a"(r) : "a"(n), "b"(a) : "memory");
    return r;
}

static int sys2(int n, int a, int b)
{
    int r;
    __asm__ volatile("int $0x80" : "=a"(r) : "a"(n), "b"(a), "c"(b) : "memory");
    return r;
}

static int sys3(int n, int a, int b, int c)
{
    int r;
    __asm__ volatile("int $0x80" : "=a"(r) : "a"(n), "b"(a), "c"(b), "d"(c) : "memory");
    return r;
}

static int sys4(int n, int a, int b, int c, int d)
{
    int r;
    __asm__ volatile("int $0x80" : "=a"(r) : "a"(n), "b"(a), "c"(b), "d"(c), "S"(d) : "memory");
    return r;
}

#define SYS_exit   1
#define SYS_fork   2
#define SYS_read   3
#define SYS_open   5
#define SYS_close  6
#define SYS_execve 11
#define SYS_mkdir  39
#define SYS_wait4  114

static int xopen(const char *path)
{
    return sys3(SYS_open, (int)path, 0 /* O_RDONLY */, 0);
}

static int exists(const char *path)
{
    int fd = xopen(path);
    if (fd < 0)
        return 0;
    sys1(SYS_close, fd);
    return 1;
}

/* mkdir -p; the path is modified in place while it is walked */
static void mkdir_p(char *path)
{
    char *p;
    for (p = path + 1; *p; p++) {
        if (*p == '/') {
            *p = 0;
            sys2(SYS_mkdir, (int)path, 0755);
            *p = '/';
        }
    }
    sys2(SYS_mkdir, (int)path, 0755);
}

/* run a command and return its exit status, or -1 */
static int run(char **av)
{
    char *ev[2];
    int pid, status = 0;

    ev[0] = "PATH=/";
    ev[1] = 0;

    pid = sys0(SYS_fork);
    if (pid < 0)
        return -1;
    if (pid == 0) {
        sys3(SYS_execve, (int)av[0], (int)av, (int)ev);
        sys1(SYS_exit, 127);
    }
    status = 0;
    if (sys4(SYS_wait4, pid, (int)&status, 0, 0) < 0)
        return -1;
    if (status & 0x7f)
        return -1;                       /* killed by a signal */
    return (status >> 8) & 0xff;
}

static char *join(const char *a, const char *b)
{
    char *r = malloc(strlen(a) + strlen(b) + 2);
    strcpy(r, a);
    strcat(r, "/");
    strcat(r, b);
    return r;
}

/* <root>/src/aio/aio.c -> <objdir>/src/aio/aio.o */
static char *objname(const char *objdir, const char *src)
{
    char *o = join(objdir, src);
    char *dot = strrchr(o, '.');
    if (dot != 0 && strchr(dot, '/') == 0)
        strcpy(dot, ".o");
    else
        strcat(o, ".o");
    return o;
}

/* read a whole file into buf; returns its length or -1 */
static int readfile(const char *path, char *buf, int max)
{
    int fd, n, total = 0;
    fd = xopen(path);
    if (fd < 0)
        return -1;
    while (total < max - 1) {
        n = sys3(SYS_read, fd, (int)(buf + total), max - 1 - total);
        if (n <= 0)
            break;
        total += n;
    }
    sys1(SYS_close, fd);
    buf[total] = 0;
    return total;
}

/* iterate over the lines of the list; returns the next line or 0 */
static char *nextline(char **pp)
{
    char *p = *pp, *e;
    int last;
    if (*p == 0)
        return 0;
    e = strchr(p, '\n');
    last = (e == 0);
    if (last)
        e = p + strlen(p);
    *e = 0;
    *pp = last ? e : e + 1;
    return p;
}

int main(int argc, char **argv)
{
    char *mode, *cc, *cflags, *root, *objdir, *list, *archive = 0;
    char *buf, *p, *line, *atcflags, **av;
    int len, n, ok = 0, bad = 0, rc;

    if (argc < 7) {
        printf("usage: tcbuild c|a <cc> <cflags|-> <root> <objdir> <list> [archive]\n");
        return 2;
    }
    mode = argv[1];
    cc = argv[2];
    cflags = argv[3];
    root = argv[4];
    objdir = argv[5];
    list = argv[6];
    if (argc > 7)
        archive = argv[7];

    buf = malloc(1 << 20);
    av = malloc(4096 * sizeof(char *));
    len = readfile(list, buf, 1 << 20);
    if (len < 0) {
        printf("tcbuild: cannot read list file %s\n", list);
        return 1;
    }

    atcflags = malloc(strlen(cflags) + 2);
    strcpy(atcflags, "@");
    strcat(atcflags, cflags);

    if (mode[0] == 'c') {
        p = buf;
        while ((line = nextline(&p)) != 0) {
            char *src, *obj, *slash;
            if (*line == 0 || *line == '#')
                continue;
            src = join(root, line);
            obj = objname(objdir, line);
            slash = strrchr(obj, '/');
            if (slash != 0) {
                *slash = 0;
                mkdir_p(obj);
                *slash = '/';
            }
            n = 0;
            av[n++] = cc;
            if (strcmp(cflags, "-") != 0)
                av[n++] = atcflags;
            av[n++] = "-c";
            av[n++] = src;
            av[n++] = "-o";
            av[n++] = obj;
            av[n] = 0;
            rc = run(av);
            if (rc != 0) {
                printf("  skip %s (compiler exit %d)\n", line, rc);
                bad++;
            } else {
                ok++;
            }
            if ((ok + bad) % 200 == 0)
                printf("  ... %d compiled, %d skipped\n", ok, bad);
        }
        printf("tcbuild: compiled %d, skipped %d\n", ok, bad);
        return 0;
    }

    /* archive mode */
    av[0] = cc;
    av[1] = "-ar";
    av[2] = "-cr";
    av[3] = archive;
    n = 4;
    p = buf;
    while ((line = nextline(&p)) != 0) {
        char *obj;
        if (*line == 0 || *line == '#')
            continue;
        obj = objname(objdir, line);
        if (exists(obj))
            av[n++] = obj;
    }
    av[n] = 0;
    printf("tcbuild: archiving %d objects into %s\n", n - 4, archive);
    rc = run(av);
    printf("tcbuild: archive %s (exit %d)\n", archive, rc);
    return rc != 0;
}
