#!/bin/bash
#
# 3-build-deps-gcc46.sh — rebuild the four libraries (GMP 6.2.1 / MPFR 4.1.0 /
#   MPC 1.2.1 / zlib 1.3.2) with the **first-generation gcc46 (stage1) + musl-gcc**,
#   overwriting the copies installed in the global sysroot
#   `rootfs3/usr/{include,lib}`.
#
# Why this step exists:
#   Up to and including ./3-build-gcc46-stage2.sh, the `libgmp.a`/`libmpfr.a`/
#   `libmpc.a`/`libz.a` linked into that stage2 `cc1`/`cc1plus` are **still xcc
#   output** — the last piece of "xcc code generation" inside those binaries.
#   Following the bootstrap rule "build the dependencies with the previous
#   generation's compiler, then build the next compiler":
#       first-generation gcc46 (stage1) → rebuild the four libraries → rebuild
#       stage2 with them (`CLEAN=1 ./3-build-gcc46-stage2.sh`)
#   after which the stage2 compilers are genuinely produced by a GCC-only chain.
#   This also sets up the next generation: GCC 10.4.0 links the same GMP 6.2.1 from
#   the global sysroot, so that copy has to come from a real GCC as well.
#
# Setup (same compiler and target libc as ./3-build-gcc46-stage2.sh):
#   * CC = `$ROOTFS/build/deps-gcc46/cc-gcc46`, generated by this script:
#       `stage1 xgcc -B$S1/gcc --sysroot=$SYSROOT -isystem $DEPS/include -L$MUSL_GCC/lib`
#     — the **first-generation gcc46**, with the target libc = **musl-gcc** (the musl
#     that gcc46 rebuilt in full).
#   * The four library scripts themselves are **unchanged**: only `CC_WRAP=…` (which
#     replaces their default `xcc-musl-cc`), `CLEAN=1` (a compiler switch does not
#     make make rebuild existing .o files, so the build tree has to be cleared),
#     `CHECK=…` and `JOBS=…` are passed in.
#   * `-L$MUSL_GCC/lib` **must come first**: the libraries' own smoke tests add
#     `-L$ROOTFS/usr/lib`, which holds both the four libraries and a `libc.a`
#     symlink; if that directory were searched first, `-lc` could hit a different
#     musl's libc.a and mix it with musl-gcc's crt1.o (the `_DYNAMIC` link failure
#     described at the CC wrapper below).
#   * The self-tests are a gate: GMP/MPFR/MPC run `make check` via `CHECK=1`
#     (expect 175/179/69 PASS and 0 FAIL/0 ERROR), zlib runs its own `make test`.
#
# Usage:
#   ./3-build-deps-gcc46.sh                # rebuild all four + self-tests (default)
#   NO_CHECK=1 ./3-build-deps-gcc46.sh     # skip make check (faster, but no gate)
#   ONLY=gmp,mpfr ./3-build-deps-gcc46.sh  # only some of them (comma-separated; the
#                                          # order stays gmp→mpfr→mpc→zlib)
#   JOBS=n ./3-build-deps-gcc46.sh         # parallelism
#
# Output: overwrites `rootfs3/usr/include/{gmp,mpfr,mpc,zlib,zconf}.h` and
#         `rootfs3/usr/lib/{libgmp,libmpfr,libmpc,libz}.a` (in place).
# Log:    `results/3-build-deps-gcc46.log` (each library also writes
#         `results/3-build-{gmp,mpfr,mpc,zlib}.log`)
#
# Host tools — full disclosure. Apart from the first-generation gcc46 and the
# self-built binutils inside rootfs3, this script only calls the host binaries below
# (none is a compiler); the four library scripts it drives need their own set too:
#   bash make sed awk grep find cp mv rm mkdir ln cat head tail wc tr cut sort uniq
#   cmp stat sha256sum file readelf tee — required and checked at startup
#   nproc — JOBS default (not checked)
#   the four library scripts also need tar xz gzip install ar ranlib nm
#   (`ar` is the only one of those this script calls: to count archive members; it is
#    rootfs3/usr/binutils/bin/ar and falls back to the host `ar` when missing)
# Not used: host gcc/cc/clang/g++/ld/as/cpp, host /usr/include and /usr/lib.
# Compiling is done by the first-generation gcc46 + musl-gcc, assembling/linking by
# the self-built binutils.
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
ROOTFS="$ROOT/rootfs3"
S1="$ROOTFS/build/gcc-4.6.4.1"                 # first-generation gcc46 (built by ./3-build-gcc46-xcc.sh)
S1XGCC="$S1/gcc/xgcc"
MUSL_GCC="$ROOTFS/usr/musl-gcc"                # the musl that gcc46 rebuilt in full
SYSROOT="$ROOTFS/usr/musl-gcc-sysroot"         # the compiler's target sysroot view (usr -> ../musl-gcc)
DEPS="$ROOTFS/usr"                             # the four libraries are installed here (--prefix=/usr + DESTDIR)
WRAPDIR="$ROOTFS/build/deps-gcc46"
WRAP="$WRAPDIR/cc-gcc46"
LOGDIR="$ROOT/results"
LOG="$LOGDIR/3-build-deps-gcc46.log"

JOBS="${JOBS:-$(nproc)}"
NO_CHECK="${NO_CHECK:-0}"
ONLY="${ONLY:-gmp,mpfr,mpc,zlib}"

die()  { echo "error: $*" >&2; exit 1; }
warn() { echo "warning: $*" >&2; }
note() { printf '\n==> %s\n' "$*"; }

AR_TOOL="$ROOTFS/usr/binutils/bin/ar"; [ -x "$AR_TOOL" ] || AR_TOOL=ar

mkdir -p "$LOGDIR"
exec > >(tee "$LOG") 2>&1

# ---------------------------------------------------------------- 0. Preconditions
note "[0/4] checking inputs and host tools"
for f in cc1 cc1plus xgcc libgcc.a crtbegin.o; do
  [ -e "$S1/gcc/$f" ] || die "missing first-generation gcc46 output $S1/gcc/$f (run all-gcc + GOAL=all-target-libgcc of ./3-build-gcc46-xcc.sh first)"
done
[ -f "$MUSL_GCC/lib/libc.a" ] || die "missing $MUSL_GCC/lib/libc.a (run SELFTEST=1 ./3-build-musl-gcc.sh first)"
[ -f "$MUSL_GCC/lib/crt1.o" ] || die "missing $MUSL_GCC/lib/crt1.o"
[ -f "$MUSL_GCC/include/stdio.h" ] || die "missing $MUSL_GCC/include/stdio.h"
# The sysroot view used as the compiler's --sysroot; make sure it exists and create the relative link if it is missing.
mkdir -p "$SYSROOT"
[ -e "$SYSROOT/usr/include/stdio.h" ] || ln -sfn ../musl-gcc "$SYSROOT/usr"
for p in usr/include/stdio.h usr/lib/libc.a usr/lib/crt1.o usr/lib/libm.a; do
  [ -e "$SYSROOT/$p" ] || die "cannot resolve $p in the sysroot view (is $SYSROOT/usr -> ../musl-gcc correct?)"
done
for s in 3-build-gmp.sh 3-build-mpfr.sh 3-build-mpc.sh 3-build-zlib.sh; do
  [ -x "$ROOT/$s" ] || die "missing $s"
done
for t in bash make sed awk grep find cp mv rm mkdir ln cat head tail wc tr cut sort uniq cmp stat sha256sum file readelf tee; do
  command -v "$t" >/dev/null 2>&1 || die "missing host tool: $t"
done

echo "    first-gen gcc46: $("$S1XGCC" --version 2>/dev/null | head -1)  ($(sha256sum "$S1XGCC" | cut -c1-16))"
echo "    musl-gcc     : libc.a $(stat -Lc%s "$MUSL_GCC/lib/libc.a") bytes sha256=$(sha256sum "$MUSL_GCC/lib/libc.a" | cut -c1-16)"
echo "    sysroot view: $SYSROOT"
echo "    overwrite target: $DEPS/{include,lib} (--prefix=/usr + DESTDIR=$ROOTFS)"
echo "    self-test: $([ "$NO_CHECK" = 1 ] && echo 'skipped (NO_CHECK=1)' || echo 'enabled (CHECK=1 for GMP/MPFR/MPC, zlib runs its own make test)')"
echo "    libraries to build: $ONLY"

# ---------------------------------------------------------------- 1. CC wrapper
note "[1/4] writing the CC wrapper $WRAP"
mkdir -p "$WRAPDIR"
cat > "$WRAP" <<WRAP_EOF
#!/bin/sh
# Generated by 3-build-deps-gcc46.sh: the first-generation gcc46 (stage1) with the
# musl-gcc sysroot. -L$MUSL_GCC/lib comes first: the four libraries' smoke tests add
# -L$DEPS/lib, whose libc.a symlink must never win over musl-gcc's libc.a.
# -isystem $DEPS/include exposes the four libraries' own headers (gmp.h/mpfr.h/
#   mpc.h/zlib.h/zconf.h): the smoke tests #include <gmp.h> and friends directly.
#   After ./3-adjust-rootfs-current.sh those headers ARE the sysroot's musl headers,
#   so this -isystem cannot mix two musl copies.
exec $S1XGCC -B$S1/gcc --sysroot=$SYSROOT -isystem $DEPS/include -L$MUSL_GCC/lib "\$@"
WRAP_EOF
chmod 755 "$WRAP"
echo "    $(sed -n '5p' "$WRAP")"
TMPD="$ROOTFS/tests"; mkdir -p "$TMPD"
# Self-check: compile and run a small libc program (only checks whether the "first-generation gcc46 + musl-gcc" chain works).
cat > "$TMPD/3-deps-gcc46-wrapcheck.c" <<'C_EOF'
#include <stdio.h>
int main(void) { printf("deps-gcc46 cc-ok\n"); return 0; }
C_EOF
out="$("$WRAP" -o "$WRAPDIR/wrapcheck" "$TMPD/3-deps-gcc46-wrapcheck.c" && "$WRAPDIR/wrapcheck")" \
  || die "CC wrapper self-check failed (compile/run did not work)"
[ "$out" = "deps-gcc46 cc-ok" ] || die "unexpected CC wrapper self-check output: $out"
echo "    self-check: \"$out\"  ($(file -b "$WRAPDIR/wrapcheck" | cut -d, -f1-2))"

# ---------------------------------------------------------------- 2. Fingerprints of the four libraries before the rebuild (for comparison)
note "[2/4] four-library fingerprints before the rebuild (snapshot)"
for l in libgmp.a libmpfr.a libmpc.a libz.a; do
  if [ -f "$DEPS/lib/$l" ]; then
    printf '    old %-12s %9s B / %5s members / sha256 %s\n' "$l" "$(stat -c%s "$DEPS/lib/$l")" \
      "$("$AR_TOOL" t "$DEPS/lib/$l" 2>/dev/null | wc -l)" "$(sha256sum "$DEPS/lib/$l" | cut -c1-16)"
  fi
done

# ---------------------------------------------------------------- 3. Rebuild the four libraries one after another
run_one() {
  local name="$1" script="$2" check="$3"
  if ! printf '%s\n' "$ONLY" | tr ',' '\n' | grep -qx "$name"; then
    echo "    ($name not in ONLY, skipping)"
    return 0
  fi
  note "[3/4] rebuilding $name: CC_WRAP=$WRAP CLEAN=1 CHECK=$check JOBS=$JOBS ./$script"
  local rc=0
  set +e
  CC_WRAP="$WRAP" CLEAN=1 CHECK="$check" JOBS="$JOBS" "$ROOT/$script" > "/dev/null" 2>&1
  rc=$?
  set -e
  local lg="$LOGDIR/3-build-$name.log"
  if [ "$rc" != 0 ]; then
    echo "    ❌ $name failed (exit code $rc) — log tail:"
    tail -25 "$lg" 2>/dev/null | sed 's/^/      /'
    die "$name build failed (full log $lg)"
  fi
  echo "    ✅ $name exit code 0 (log $lg)"
  grep -E 'test totals:|zlib test OK|sha256|checksum|lib(gmp|mpfr|mpc|z)\.a' "$lg" 2>/dev/null | tail -4 | sed 's/^/      /' || true
}

run_one gmp  "3-build-gmp.sh"  "$([ "$NO_CHECK" = 1 ] && echo 0 || echo 1)"
run_one mpfr "3-build-mpfr.sh" "$([ "$NO_CHECK" = 1 ] && echo 0 || echo 1)"
run_one mpc  "3-build-mpc.sh"  "$([ "$NO_CHECK" = 1 ] && echo 0 || echo 1)"
run_one zlib "3-build-zlib.sh" "$([ "$NO_CHECK" = 1 ] && echo 0 || echo 1)"   # CHECK=1 → also run zlib's own make test

# ---------------------------------------------------------------- 4. Summary + self-test gate
note "[4/4] four-library fingerprints after the rebuild and self-test results"
gmp_ok=0; mpfr_ok=0; mpc_ok=0; zlib_ok=0
for l in libgmp.a libmpfr.a libmpc.a libz.a; do
  [ -f "$DEPS/lib/$l" ] || die "missing after the rebuild: $DEPS/lib/$l"
  printf '    new %-12s %9s B / %5s members / sha256 %s\n' "$l" "$(stat -c%s "$DEPS/lib/$l")" \
    "$("$AR_TOOL" t "$DEPS/lib/$l" 2>/dev/null | wc -l)" "$(sha256sum "$DEPS/lib/$l" | cut -c1-16)"
done
for h in gmp.h mpfr.h mpc.h zlib.h zconf.h; do
  [ -f "$DEPS/include/$h" ] || die "missing after the rebuild: $DEPS/include/$h"
done

if [ "$NO_CHECK" != 1 ]; then
  echo
  echo "    --- self-test gate (the gate is FAIL=0 / ERROR=0; GMP expects 175, MPFR 179+4 SKIP, MPC 69, zlib make test OK) ---"
  for pair in "gmp:3-build-gmp.log" "mpfr:3-build-mpfr.log" "mpc:3-build-mpc.log"; do
    n="${pair%%:*}"; f="$LOGDIR/${pair##*:}"
    line="$(grep -E 'test totals:' "$f" 2>/dev/null | tail -1 || true)"
    echo "      $n: ${line:-(no self-test summary line found, see $f)}"
    case "$n" in
      gmp)  printf '%s' "$line" | grep -q 'FAIL=0' && printf '%s' "$line" | grep -q 'ERROR=0' && gmp_ok=1 ;;
      mpfr) printf '%s' "$line" | grep -q 'FAIL=0' && printf '%s' "$line" | grep -q 'ERROR=0' && mpfr_ok=1 ;;
      mpc)  printf '%s' "$line" | grep -q 'FAIL=0' && printf '%s' "$line" | grep -q 'ERROR=0' && mpc_ok=1 ;;
    esac
  done
  # MPFR's harness can mark a test SKIP (exit code 77, the automake convention) for
  # feature-dependent cases; SKIP is not FAIL, so the gate stays FAIL=0/ERROR=0.
  mpfr_skip="$(grep -cE '^SKIP: ' "$LOGDIR/3-build-mpfr.log" 2>/dev/null || true)"
  [ "${mpfr_skip:-0}" = 0 ] || echo "      mpfr: $mpfr_skip further cases were marked SKIP by MPFR's own harness (not a failure)"
  # zlib: with CHECK=1 the zlib script runs zlib's own make test; on success that
  # prints an OK marker and leaves *** zlib test OK *** in check.log — either one
  # satisfies the gate.
  if grep -qE 'self-test OK|zlib test OK' "$LOGDIR/3-build-zlib.log" 2>/dev/null; then zlib_ok=1; fi
  echo "      zlib: $(grep -oE 'self-test (OK|FAIL)' "$LOGDIR/3-build-zlib.log" 2>/dev/null | tail -1 || echo '(no zlib self-test verdict found)')"
  [ "$gmp_ok"  = 1 ] || die "GMP self-test has FAIL/ERROR (see $LOGDIR/3-build-gmp.log)"
  [ "$mpfr_ok" = 1 ] || die "MPFR self-test has FAIL/ERROR (see $LOGDIR/3-build-mpfr.log)"
  [ "$mpc_ok"  = 1 ] || die "MPC self-test has FAIL/ERROR (see $LOGDIR/3-build-mpc.log)"
  [ "$zlib_ok" = 1 ] || die "zlib's own make test did not pass (see $LOGDIR/3-build-zlib.log)"
  echo "    ✅ all four library self-tests green"
fi

# ---------------------------------------------------------------- Record state
source "$ROOT/3-lib/common.sh" 2>/dev/null || true
if command -v record >/dev/null 2>&1; then
  record DEPS_GCC46_WRAP "$WRAP"
  record DEPS_GCC46_SYSROOT "$SYSROOT"
  record DEPS_GCC46_GMP_SIZE "$(stat -c%s "$DEPS/lib/libgmp.a" 2>/dev/null || echo 0)"
  record DEPS_GCC46_GMP_SHA256 "$(sha256sum "$DEPS/lib/libgmp.a" 2>/dev/null | cut -c1-16 || echo -)"
  record DEPS_GCC46_MPFR_SIZE "$(stat -c%s "$DEPS/lib/libmpfr.a" 2>/dev/null || echo 0)"
  record DEPS_GCC46_MPFR_SHA256 "$(sha256sum "$DEPS/lib/libmpfr.a" 2>/dev/null | cut -c1-16 || echo -)"
  record DEPS_GCC46_MPC_SIZE "$(stat -c%s "$DEPS/lib/libmpc.a" 2>/dev/null || echo 0)"
  record DEPS_GCC46_MPC_SHA256 "$(sha256sum "$DEPS/lib/libmpc.a" 2>/dev/null | cut -c1-16 || echo -)"
  record DEPS_GCC46_ZLIB_SIZE "$(stat -c%s "$DEPS/lib/libz.a" 2>/dev/null || echo 0)"
  record DEPS_GCC46_ZLIB_SHA256 "$(sha256sum "$DEPS/lib/libz.a" 2>/dev/null | cut -c1-16 || echo -)"
  record DEPS_GCC46_SELFTEST_OK "$([ "$NO_CHECK" = 1 ] && echo skipped || echo 1)"
fi

note "done (log: $LOG)"
cat <<EOF
  four libraries overwritten at: $DEPS/{include,lib}
  next (rebuild stage2 with these new four libraries):
      CLEAN=1 ./3-build-gcc46-stage2.sh
  then (point the rootfs commands at the newest gcc/musl/libraries):
      ./3-adjust-rootfs-current.sh
EOF
